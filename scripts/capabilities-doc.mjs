#!/usr/bin/env node
/**
 * Writes docs/capabilities.md from each plugin's `catalog` (src/plugins/contract.ts),
 * the one source for what each role does, needs, and what happens without it.
 *
 *   node scripts/capabilities-doc.mjs           # write the doc (after npm run build)
 *   node scripts/capabilities-doc.mjs --check   # exit 1 if the doc is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = (p) => pathToFileURL(join(root, "dist", p)).href;
if (!existsSync(join(root, "dist/plugins/index.js"))) {
  console.error("capabilities-doc: run npm run build first");
  process.exit(2);
}
const { registerBuiltinPlugins } = await import(dist("plugins/index.js"));
const { registeredPlugins } = await import(dist("plugins/registry.js"));
// Plugin constructors only keep the runtime; the catalog never reads it.
registerBuiltinPlugins({ builds: { isInFlight: () => false } });

function render(plugins) {
  const code = (xs) => (xs.length ? xs.map((x) => `\`${x}\``).join(", ") : "none");
  const out = [
    "# Capabilities",
    "",
    "<!-- Generated by scripts/capabilities-doc.mjs from each plugin's `catalog`. Do not edit by hand. -->",
    "",
    "Every role below is optional except a work source and a code host. Turn on the ones your team has;",
    "for each one left off, **When off** says what the Foreman does instead. `npm run doctor` checks the result.",
    "",
    "| Plugin | Roles | On when |",
    "|---|---|---|",
    ...plugins.map((p) => `| ${p.catalog.name} (\`${p.id}\`) | ${code(p.roles)} | ${p.catalog.onWhen} |`),
    "",
  ];
  for (const p of plugins) {
    const c = p.catalog;
    out.push(
      `## ${c.name} (\`${p.id}\`)`,
      "",
      c.purpose,
      "",
      `- **Roles:** ${code(p.roles)}`,
      `- **On when:** ${c.onWhen}`,
      `- **Config:** ${code(c.requires.config)}`,
      `- **Env:** ${code(c.requires.env)}`,
      `- **When off:** ${c.whenOff}`,
      "",
    );
  }
  return out.join("\n");
}

const path = join(root, "docs/capabilities.md");
const want = render(registeredPlugins());
if (process.argv.includes("--check")) {
  const have = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (have !== want) {
    console.error("docs/capabilities.md is stale: run npm run build && node scripts/capabilities-doc.mjs");
    process.exit(1);
  }
  console.log("docs/capabilities.md matches the plugin catalog");
} else {
  writeFileSync(path, want);
  console.log(`wrote ${path}`);
}
